export function t(locale: AppLocale, key: CopyKey) {
  return messages[locale]?.[key] ?? messages[DEFAULT_LOCALE][key];
}

export function feedbackFor(locale: AppLocale, tone: 'good' | 'bad') {
  return feedback[locale]?.[tone] ?? feedback[DEFAULT_LOCALE][tone];
}

export function localize(text: LocalizedText, locale: AppLocale) {
  return text[locale] ?? text[DEFAULT_LOCALE];
}

export function detectLocale(): AppLocale {
  const locale = getLocales()[0]?.languageTag?.toLowerCase() ?? '';
  const language = getLocales()[0]?.languageCode?.toLowerCase() ?? '';
  const region = getLocales()[0]?.regionCode?.toUpperCase() ?? '';

  if (locale.includes('hant') || locale.includes('tw') || locale.includes('hk') || locale.includes('mo')) {
    return 'zh-Hant';
  }

  if (language === 'zh') return 'zh-Hans';
  if (language === 'fr') return 'fr';
  if (language === 'it') return 'it';
  if (language === 'de') return 'de';
  if (language === 'es') return 'es-ES';
  if (language === 'ko') return 'ko';
  if (language === 'pl') return 'pl';
  if (language === 'pt' && region === 'BR') return 'pt-BR';
  if (language === 'pt') return 'pt-BR';
  return DEFAULT_LOCALE;
}

export function makeText(
  enText: string,
  zhHans: string,
  _jaText: string,
  koText: string,
  overrides: Partial<Record<AppLocale, string>> = {},
): LocalizedText {
  return {
    en: enText,
    'zh-Hans': zhHans,
    'zh-Hant': overrides['zh-Hant'] ?? toTraditionalChinese(zhHans),
    fr: overrides.fr ?? contentTranslation(enText, 'fr'),
    it: overrides.it ?? contentTranslation(enText, 'it'),
    de: overrides.de ?? contentTranslation(enText, 'de'),
    'es-ES': overrides['es-ES'] ?? contentTranslation(enText, 'es-ES'),
    ko: koText,
    pl: overrides.pl ?? contentTranslation(enText, 'pl'),
    'pt-BR': overrides['pt-BR'] ?? contentTranslation(enText, 'pt-BR'),
  };
}

